#!/bin/zsh
# ==============================================================================
# Chapter 01 · 실습 04 - Linux & macOS 프로세스 및 PID 관리 자동화 스크립트
# ==============================================================================

echo "=================================================="
echo "STEP 1. 백그라운드 프로세스 생성 (sleep 300 &)"
echo "=================================================="
sleep 300 &
PID=$!
echo "-> 백그라운드로 실행된 프로세스 PID: $PID"

echo "\n=================================================="
echo "STEP 2. 프로세스 상태 상세 조회 (ps & jobs)"
echo "=================================================="
echo "[jobs -l 결과 - 현재 셸이 관리하는 작업]"
jobs -l

echo "\n[ps 결과 - 커널이 관리하는 프로세스 메타데이터]"
ps -p "$PID" -o pid,ppid,stat,%cpu,%mem,comm

echo "\n=================================================="
echo "STEP 3. 안전한 프로세스 종료 (kill -TERM $PID)"
echo "=================================================="
echo "-> SIGTERM(15) 정상 종료 시그널 전송 중..."
kill -TERM "$PID"

# 프로세스가 종료될 수 있도록 잠시 대기
sleep 1

echo "\n=================================================="
echo "STEP 4. 종료 여부 최종 검증"
echo "=================================================="
if ps -p "$PID" > /dev/null 2>&1; then
    echo "[경고] 프로세스(PID: $PID)가 아직 실행 중입니다."
else
    echo "[성공] 프로세스(PID: $PID)가 안전하게 종료되었습니다 (No such process)."
fi
